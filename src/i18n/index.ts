const completeResources = Object.fromEntries(
  Object.entries(resources).map(([locale, bundle]) => {
    if (locale === 'zh-CN' || locale === 'en-US') return [locale, bundle];
    return [
      locale,
      {
        translation: deepMergeTranslations(
          deepMergeTranslations(
            resources['en-US'].translation as TranslationTree,
            bundle.translation as TranslationTree,
          ),
          localeEnhancements[locale]?.translation || {},
        ),
      },
    ];
  }),
) as typeof resources;

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources: completeResources,
    lng: undefined,
    fallbackLng: {
      'zh-CN': ['zh-CN'],
      'en-US': ['en-US', 'zh-CN'],
      'ja-JP': ['ja-JP', 'en-US', 'zh-CN'],
      'ko-KR': ['ko-KR', 'en-US', 'zh-CN'],
      'es-ES': ['es-ES', 'en-US', 'zh-CN'],
      'fr-FR': ['fr-FR', 'en-US', 'zh-CN'],
      default: ['en-US', 'zh-CN'],
    },
    // 默认面向中文家庭；只有用户主动在设置里切换语言后，才读取本地保存的选择。
    detection: {
      order: ['localStorage'],
      caches: ['localStorage'],
      lookupLocalStorage: 'i18nextLng',
      convertDetectedLanguage: (lng: string) => {
        const supported = ['zh-CN', 'en-US', 'ja-JP', 'ko-KR', 'es-ES', 'fr-FR'];
        return supported.includes(lng) ? lng : 'zh-CN';
      },
    },
    interpolation: {
      escapeValue: false,
    },
    // 当翻译缺失时，返回键名本身（便于识别缺失的翻译）
    saveMissing: false,
    missingKeyHandler: (lng, ns, key) => {
      if (process.env.NODE_ENV === 'development') {
        console.warn(`Missing translation key: ${key} for language: ${lng}`);
      }
    },
    // 在开发模式下启用调试日志
    debug: false,
  });

export default i18n;
