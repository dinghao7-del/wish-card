type TranslationTree = Record<string, unknown>;

function deepMergeTranslations(base: TranslationTree, override: TranslationTree): TranslationTree {
  const merged: TranslationTree = { ...base };
  Object.entries(override).forEach(([key, value]) => {
    const baseValue = merged[key];
    if (
      value &&
      baseValue &&
      typeof value === 'object' &&
      typeof baseValue === 'object' &&
      !Array.isArray(value) &&
      !Array.isArray(baseValue)
    ) {
      merged[key] = deepMergeTranslations(baseValue as TranslationTree, value as TranslationTree);
      return;
    }
    merged[key] = value;
  });
  return merged;
}

